/*
 * MT6391 (MT6397 PMIC) audio codec registers
 *
 * The analogue registers are in <linux/mfd/mt6397/registers.h>; this adds
 * the PMIC's audio digital block and the fields the codec driver uses. Field
 * names follow MediaTek's MT6397 register map, which leaves AFUNC_AUD_CON2's
 * unnamed; those follow the MT6358's register of the same layout.
 *
 * Copyright (c) 2026 Ryan Brue <ryanbrue.dev@gmail.com>
 */

#ifndef __MT6391_H__
#define __MT6391_H__

#include <linux/bits.h>

#define MT6397_TOP_RST_CON_SET		0x0116
#define MT6397_TOP_RST_CON_CLR		0x0118

/* Accessory detection (ACCDET) */
#define MT6397_ACCDET_CON0		0x0584
#define MT6397_ACCDET_CON1		0x0586
#define MT6397_ACCDET_CON2		0x0588
#define MT6397_ACCDET_CON3		0x058a
#define MT6397_ACCDET_CON4		0x058c
#define MT6397_ACCDET_CON5		0x058e
#define MT6397_ACCDET_CON6		0x0590
#define MT6397_ACCDET_CON7		0x0592
#define MT6397_ACCDET_CON9		0x0596
#define MT6397_ACCDET_CON11		0x059a
#define MT6397_ACCDET_CON13		0x059e

/* Audio digital block */
#define MT6397_AFE_UL_DL_CON0		0x4000
#define MT6397_AFE_DL_SRC2_CON0_H	0x4002
#define MT6397_AFE_DL_SRC2_CON0_L	0x4004
#define MT6397_AFE_DL_SDM_CON0		0x4006
#define MT6397_AFE_DL_SDM_CON1		0x4008
#define MT6397_AFE_UL_SRC_CON0_H	0x400a
#define MT6397_AFE_UL_SRC_CON0_L	0x400c
#define MT6397_AFE_UL_SRC_CON1_H	0x400e
#define MT6397_AFE_UL_SRC_CON1_L	0x4010
#define MT6397_ANA_AFE_TOP_CON0		0x4012
#define MT6397_ANA_AUDIO_TOP_CON0	0x4014
#define MT6397_AFUNC_AUD_CON0		0x401c
#define MT6397_AFUNC_AUD_CON1		0x401e
#define MT6397_AFUNC_AUD_CON2		0x4020
#define MT6397_AFUNC_AUD_CON3		0x4022
#define MT6397_AFUNC_AUD_CON4		0x4024
#define MT6397_AFE_PMIC_NEWIF_CFG0	0x4038
#define MT6397_AFE_PMIC_NEWIF_CFG1	0x403a
#define MT6397_AFE_PMIC_NEWIF_CFG2	0x403c
#define MT6397_AFE_PMIC_NEWIF_CFG3	0x403e
#define MT6397_AFE_SGEN_CFG0		0x4040
#define MT6397_AFE_SGEN_CFG1		0x4042

/* TOP_CKPDN */
#define MT6397_RG_AUD_26M_PDN		BIT(0)
#define MT6397_RG_AUD_13M_PDN		BIT(1)
#define MT6397_RG_SPK_CK_PDN		BIT(2)
#define MT6397_RG_SPK_PWM_DIV_PDN	BIT(9)
#define MT6397_RG_SPK_DIV_PDN		BIT(10)
#define MT6397_RG_ACCDET_CK_PDN		BIT(14)

/* TOP_RST_CON */
#define MT6397_RG_ACCDET_RST		BIT(4)

/* TOP_CKCON1 */
#define MT6397_RG_CLKSQ_EN		BIT(4)

/* SPK_CON0, SPK_CON3 */
#define MT6397_SPK_EN			BIT(0)
#define MT6397_SPK_TRIM_EN		BIT(3)
#define MT6397_RG_SPK_GAIN		GENMASK(15, 12)

/* SPK_CON1, SPK_CON4 */
#define MT6397_SPK_TRIM_DONE		BIT(15)
#define MT6397_SPK_OFFSET_MODE		BIT(14)
#define MT6397_SPK_LEAD_SW		BIT(13)
#define MT6397_SPK_OFFSET_SW		GENMASK(12, 8)
#define MT6397_SPK_TRIM			GENMASK(14, 8)

/* SPK_CON2, and SPK_CON5 bits 10:0 */
#define MT6397_RG_SPK_SLEW		GENMASK(3, 2)
#define MT6397_RG_SPKAB_OBIAS		GENMASK(5, 4)
#define MT6397_SPK_CTRL			GENMASK(10, 0)

/* SPK_CON5 */
#define MT6397_RG_SPKPGA_GAINR		GENMASK(14, 11)

/* SPK_CON9 */
#define MT6397_RG_SPKPGA_GAINL		GENMASK(11, 8)

/* SPK_CON11 */
#define MT6397_SPK_OUTSTG_EN_L_SW	BIT(11)
#define MT6397_SPK_OUTSTG_EN_R_SW	BIT(10)
#define MT6397_SPK_EN_L_SW		BIT(9)
#define MT6397_SPK_EN_R_SW		BIT(8)

/* AUDDAC_CON0 */
#define MT6397_RG_AUDDACLPWRUP		BIT(0)
#define MT6397_RG_AUDDACRPWRUP		BIT(1)
#define MT6397_RG_AUD_DAC_PWR_UP	BIT(2)
#define MT6397_RG_AUD_DAC_PWL_UP	BIT(3)

/* AUDBUF_CFG0 */
#define MT6397_RG_AUDHSPWRUP		BIT(0)
#define MT6397_RG_AUDHPLPWRUP		BIT(1)
#define MT6397_RG_AUDHPRPWRUP		BIT(2)
#define MT6397_RG_AUDHSMUXINPUTSEL	GENMASK(4, 3)
#define MT6397_RG_AUDHPLMUXINPUTSEL	GENMASK(8, 5)
#define MT6397_RG_AUDHPRMUXINPUTSEL	GENMASK(12, 9)
#define MT6397_HS_MUX_MUTE		1
#define MT6397_HP_MUX_AUDIO		4

/* AUDBUF_CFG1 */
#define MT6397_RG_PRECHARGEBUF_EN	BIT(6)
#define MT6397_RG_HPOUTPUTSTBENH	BIT(8)
#define MT6397_RG_HPOUT_SHORTVCM	BIT(11)

/* AUDBUF_CFG2 */
#define MT6397_RG_HSOUTPUTSTBENH	BIT(1)
#define MT6397_RG_HPOUTSTB_RSEL		GENMASK(6, 4)
#define MT6397_RG_HSOUT_SHORTVCM	BIT(7)

/* AUDBUF_CFG3 */
#define MT6397_RG_AUDHPLTRIM		GENMASK(3, 0)
#define MT6397_RG_AUDHPRTRIM		GENMASK(7, 4)
#define MT6397_RG_AUDHPTRIM_EN		BIT(8)
#define MT6397_RG_AUDHPLFINETRIM	GENMASK(10, 9)
#define MT6397_RG_AUDHPRFINETRIM	GENMASK(12, 11)
#define MT6397_HP_TRIM			GENMASK(12, 0)

/* IBIASDIST_CFG0 */
#define MT6397_RG_AUDIBIASPWRDN		BIT(12)
#define MT6397_AUDBIASADJ		0x0552

/* AUDACCDEPOP_CFG0 */
#define MT6397_RG_DEPOP_ISEL		GENMASK(5, 4)

/* AUD_IV_CFG0 */
#define MT6397_RG_AUDIVLPWRUP		BIT(0)
#define MT6397_RG_AUDIVLMUXSEL		GENMASK(4, 2)
#define MT6397_RG_AUDIVRPWRUP		BIT(8)
#define MT6397_RG_AUDIVRMUXSEL		GENMASK(12, 10)
#define MT6397_IV_MUX_AUDIO		4

/* AUDCLKGEN_CFG0 */
#define MT6397_RG_RSTB_DECODER		BIT(0)

/* AUDLDO_CFG0 */
#define MT6397_AUDLDO_DEFAULT		0x0192
#define MT6397_RG_VA33REFGEN_EN		BIT(10)
#define MT6397_RG_VA28REFGEN_EN		BIT(11)

/* AUDNVREGGLB_CFG0 */
#define MT6397_RG_AUDGLB_PWRDN		BIT(1)
#define MT6397_RG_ACC_DCC_SEL_AUDGLB	BIT(2)
#define MT6397_DA_NVREG_EN		BIT(3)

/* AUD_NCP0 */
#define MT6397_DA_LCLDO_EN		BIT(13)
#define MT6397_DA_HCLDO_EN		BIT(14)
#define MT6397_RG_NCP_REMOTE_SENSE	BIT(15)

/* ZCD_CON0 */
#define MT6397_RG_AUDZCDENABLE		BIT(0)
#define MT6397_RG_AUDZCDMUXSEL		GENMASK(10, 8)
#define MT6397_ZCD_MUX_HP		1
#define MT6397_ZCD_MUX_IV		3

/* ZCD_CON2 */
#define MT6397_RG_AUDHPLGAIN		GENMASK(3, 0)
#define MT6397_RG_AUDHPRGAIN		GENMASK(11, 8)

/* ZCD_CON3 */
#define MT6397_RG_AUDHSGAIN		GENMASK(3, 0)

/* ZCD_CON4 */
#define MT6397_RG_AUDIVLGAIN		GENMASK(2, 0)
#define MT6397_RG_AUDIVRGAIN		GENMASK(10, 8)

/* NCP_CLKDIV_CON0 */
#define MT6397_RG_DIVCKS_PRG		GENMASK(8, 0)
#define MT6397_RG_DIVCKS_ON		BIT(12)

/* NCP_CLKDIV_CON1 */
#define MT6397_RG_PWD_NCP		BIT(0)

/* ACCDET_CON1 */
#define MT6397_ACCDET_EN		BIT(0)

/* ACCDET_CON2 */
#define MT6397_ACCDET_CMP_EN		BIT(0)
#define MT6397_ACCDET_VTH_EN		BIT(1)
#define MT6397_ACCDET_MBIAS_EN		BIT(2)
#define MT6397_ACCDET_CMP_PWM_IDLE	BIT(4)
#define MT6397_ACCDET_VTH_PWM_IDLE	BIT(5)
#define MT6397_ACCDET_MBIAS_PWM_IDLE	BIT(6)

/* ACCDET_CON5 */
#define MT6397_ACCDET_FALL_DELAY	BIT(15)
#define MT6397_ACCDET_RISE_DELAY	GENMASK(14, 0)

/* ACCDET_CON11 */
#define MT6397_ACCDET_IRQ		BIT(0)
#define MT6397_ACCDET_IRQ_CLR		BIT(8)

/* ACCDET_CON13 */
#define MT6397_ACCDET_MEM_IN		GENMASK(7, 6)

/* AFE_DL_SRC2_CON0_H */
#define MT6397_DL_2_INPUT_MODE		GENMASK(15, 12)

/* AFE_DL_SRC2_CON0_L */
#define MT6397_DL_2_SRC_ON		BIT(0)

/* AFUNC_AUD_CON2 */
#define MT6397_CCI_AUD_DAC_ANA_MUTE	BIT(7)

/* ANA_AFE_TOP_CON0 */
#define MT6397_DL_SINE_ON		BIT(0)

/* AFE_PMIC_NEWIF_CFG0 */
#define MT6397_NEWIF_DL_RATE		GENMASK(15, 12)

/* AFE_PMIC_NEWIF_CFG2 */
#define MT6397_NEWIF_SCK_INV		BIT(15)

/* AFE_SGEN_CFG0 */
#define MT6397_SGEN_DAC_EN		BIT(7)

#endif
